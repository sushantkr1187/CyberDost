/**
 * Tests an RSA modulus for ROCA (Return of Coppersmith\'s Attack - CVE-2017-15361)
 * ROCA occurs when primes have the form p = k*M + (65537^a mod M).
 * A modulus N = p*q will satisfy specific modular residues mod small primes.
 */
function testROCA(modulusBigInt) {
  if (!modulusBigInt || modulusBigInt <= 0n) {
    return { isVulnerable: false, confidence: 0, reason: 'Invalid or missing modulus' };
  }

  // Precomputed allowed residues for ROCA order tests for small primes
  // For each prime P, we check if N mod P is an allowed product of elements of subgroup generated by 65537 mod P
  let matches = 0;
  let totalTests = 0;

  for (const prime of ROCA_PRIMES) {
    const pBig = BigInt(prime);
    const modN = modulusBigInt % pBig;

    // Build subgroup generated by 65537 mod prime
    const gen = 65537n % pBig;
    const subgroup = new Set();
    let current = 1n;
    for (let i = 0; i < prime; i++) {
      subgroup.add(current);
      current = (current * gen) % pBig;
      if (current === 1n) break;
    }

    // Possible products of subgroup elements
    const allowedProducts = new Set();
    for (const a of subgroup) {
      for (const b of subgroup) {
        allowedProducts.add((a * b) % pBig);
      }
    }

    totalTests++;
    if (allowedProducts.has(modN)) {
      matches++;
    }
  }

  const matchRatio = matches / totalTests;
  // Non-vulnerable keys have matchRatio significantly below 0.65; ROCA keys have 1.0 (100% matches)
  const isVulnerable = matchRatio === 1.0;

  return {
    isVulnerable,
    matchRatio: Number(matchRatio.toFixed(3)),
    confidence: isVulnerable ? 0.99 : 0.0,
    details: isVulnerable
      ? 'CRITICAL: Key matches the Infineon ROCA (CVE-2017-15361) weak prime pattern. Private key can be factored!'
      : 'Modulus passed ROCA modular subgroup distribution tests.'
  };
}

/**
 * Tests an RSA public key against weak key generation, eMudhra signatures, and PRNG flaws
 */
function auditPublicKey(pubKeyDetails) {
  const issues = [];
  const findings = [];
  let riskScore = 0; // 0 to 100

  if (!pubKeyDetails) {
    return {
      status: 'UNKNOWN',
      riskScore: 20,
      issues: ['Public key details could not be extracted'],
      findings: []
    };
  }

  const { asymmetricKeyType, modulusLength, publicExponent, curve } = pubKeyDetails;

  // 1. Key Type & Length Evaluation
  if (asymmetricKeyType === 'rsa') {
    if (modulusLength < 1024) {
      issues.push({
        severity: 'CRITICAL',
        title: 'Extremely Weak RSA Key Length (< 1024 bits)',
        desc: `Modulus length is only ${modulusLength} bits. This can be factored in minutes with commodity hardware.`
      });
      riskScore += 80;
    } else if (modulusLength < 2048) {
      issues.push({
        severity: 'HIGH',
        title: 'Deprecated RSA Key Length (< 2048 bits)',
        desc: `Modulus length is ${modulusLength} bits. CA/B Forum Baseline Requirements mandate at least 2048 bits.`
      });
      riskScore += 50;
    } else if (modulusLength === 2048) {
      findings.push({
        status: 'ACCEPTABLE',
        title: 'Standard RSA 2048-bit Key',
        desc: 'Meets current baseline industry security standards.'
      });
    } else if (modulusLength >= 4096) {
      findings.push({
        status: 'EXCELLENT',
        title: 'High Security RSA 4096-bit Key',
        desc: 'Provides enhanced cryptographic security against factoring attacks.'
      });
    }

    // 2. Public Exponent Evaluation
    if (publicExponent) {
      const expBig = BigInt(publicExponent);
      if (expBig === 3n) {
        issues.push({
          severity: 'MEDIUM',
          title: 'Low Public Exponent (e = 3)',
          desc: 'Exponents like e=3 are vulnerable to Coppersmith\'s small root attacks and message broadcast attacks if padding is flawed.'
        });
        riskScore += 25;
      } else if (expBig === 65537n) {
        findings.push({
          status: 'GOOD',
          title: 'Standard Fermat Exponent F4 (e = 65537)',
          desc: 'Standard secure exponent resistant to known small exponent attacks.'
        });
      } else if (expBig % 2n === 0n) {
        issues.push({
          severity: 'CRITICAL',
          title: 'Even Public Exponent',
          desc: 'An even exponent in RSA violates algebraic prerequisites for invertibility.'
        });
        riskScore += 90;
      }
    }
  } else if (asymmetricKeyType === 'ec' || asymmetricKeyType === 'ecdsa') {
    if (curve && (curve.includes('256') || curve.includes('384') || curve.includes('521') || curve.includes('ed25519'))) {
      findings.push({
        status: 'EXCELLENT',
        title: `Modern Elliptic Curve (${curve})`,
        desc: 'Elliptic curve cryptography provides strong security with compact key sizes.'
      });
    } else {
      issues.push({
        severity: 'MEDIUM',
        title: `Non-standard or Legacy Curve (${curve || 'unknown'})`,
        desc: 'Recommended curves are prime256v1 (secp256r1) or secp384r1.'
      });
      riskScore += 20;
    }
  }

  return {
    asymmetricKeyType: asymmetricKeyType || 'unknown',
    modulusLength: modulusLength || 0,
    publicExponent: publicExponent ? String(publicExponent) : null,
    curve: curve || null,
    riskScore: Math.min(riskScore, 100),
    issues,
    findings
  };
}

/**
 * Inspects Certificate Authority (CA) against known advisories, root trustworthiness,
 * and the eMudhra TLS incident patterns.
 */
function auditCertificateAuthority(issuerString, certInfo = {}) {
  const matchingAdvisories = [];
  let isDistrusted = false;
  let isAutomatedDV = false;
  let hasKeygenAdvisory = false;

  for (const adv of CA_ADVISORIES) {
    if (adv.caPattern.test(issuerString || '')) {
      matchingAdvisories.push(adv);
      if (adv.severity === 'CRITICAL') isDistrusted = true;
      if (adv.id === 'emudhra-incident') hasKeygenAdvisory = true;
      if (adv.id === 'free-automated-dv') isAutomatedDV = true;
    }
  }

  // eMudhra Specific Heuristic Checks:
  // In the eMudhra incident, subscriber certificates issued during affected windows or without proper CT logs were flagged.
  const eMudhraAnalysis = {
    isEMudhraCA: /emudhra/i.test(issuerString || ''),
    flaggedParameters: [],
    auditStatus: 'PASS'
  };

  if (eMudhraAnalysis.isEMudhraCA) {
    eMudhraAnalysis.auditStatus = 'WARNING';
    eMudhraAnalysis.flaggedParameters.push('Issuer matches eMudhra TLS root/sub-CA with known historic keygen audit warnings.');

    // Check if key is weaker than 2048 or has timing discrepancies
    if (certInfo.modulusLength && certInfo.modulusLength < 2048) {
      eMudhraAnalysis.auditStatus = 'FAIL';
      eMudhraAnalysis.flaggedParameters.push('Subscriber RSA key under 2048 bits under eMudhra CA.');
    }

    if (!certInfo.hasSCTs) {
      eMudhraAnalysis.flaggedParameters.push('Missing Certificate Transparency SCTs on eMudhra certificate.');
    }
  }

  return {
    issuer: issuerString,
    isDistrusted,
    isAutomatedDV,
    hasKeygenAdvisory,
    advisories: matchingAdvisories,
    eMudhraAnalysis
  };
}

